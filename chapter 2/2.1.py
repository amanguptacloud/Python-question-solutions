# 1. Two-number calculator  
# Take two numbers from the user and print their sum, difference, product, quotient, and remainder.

a=int(input("give 1st number: \n"))
b=int(input("give 2nd number: \n"))

print("sum: ",a+b)
print("difference: ",a-b)
print("product: ",a*b)
print("quotient: ",a/b)
print("remainder: ",a%b)